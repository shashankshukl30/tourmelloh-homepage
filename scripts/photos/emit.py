"""Write content/catalog/media.ts from research/photo-library.json (python scripts/photos/emit.py)."""
import base64, io, json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
lib = json.load(open(os.path.join(ROOT, "research", "photo-library.json"), encoding="utf-8"))
plan = re.findall(r'^\s+"([a-z0-9-]+)":', open(os.path.join(ROOT, "content", "catalog", "media-plan.ts"), encoding="utf-8").read(), re.M)
missing = [k for k in plan if k not in lib]
if missing:
    raise SystemExit(f"no photograph for: {missing}")


def blur(path):
    with Image.open(path) as im:
        im = im.convert("RGB")
        im.thumbnail((16, 16))
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=40)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


lines = [
    "// Generated by scripts/photos/emit.py from research/photo-library.json. Do not edit by hand.",
    'import type { MediaKey } from "./media-plan";',
    "",
    "export type Photo = {",
    "  src: string;",
    "  width: number;",
    "  height: number;",
    "  alt: string;",
    "  blur: string;",
    "  by: string;",
    "  page: string;",
    "  /** True when the licence asks for a credit (listed on /photo-credits). */",
    "  credit: boolean;",
    "  licenseName: string;",
    "  license: string;",
    "};",
    "",
    "export const media: Record<MediaKey, Photo> = {",
]
for key in plan:
    r = lib[key]
    item = {
        "src": r["src"], "width": r["width"], "height": r["height"], "alt": r["alt"],
        "blur": blur(os.path.join(ROOT, "public", r["src"].lstrip("/"))),
        "by": r["by"], "page": r["page"], "credit": bool(r.get("credit")),
        "licenseName": r.get("licenseName", "Pexels License"), "license": r["license"],
    }
    lines.append(f"  {json.dumps(key)}: {json.dumps(item, ensure_ascii=False)},")
lines += ["};", "", "export const photo = (key: MediaKey) => media[key];", ""]
open(os.path.join(ROOT, "content", "catalog", "media.ts"), "w", encoding="utf-8").write("\n".join(lines))
print(len(plan), "photographs written to content/catalog/media.ts")
